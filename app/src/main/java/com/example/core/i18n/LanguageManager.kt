object LanguageManager {
    // Default to Persian as requested by the user
    private val _currentLanguage = MutableStateFlow(AppLanguage.PERSIAN)
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    fun setLanguage(language: AppLanguage) {
        _currentLanguage.value = language
    }

    fun toggleLanguage() {
        if (_currentLanguage.value == AppLanguage.PERSIAN) {
            setLanguage(AppLanguage.ENGLISH)
        } else {
            setLanguage(AppLanguage.PERSIAN)
        }
    }

    val isPersian: Boolean
        get() = _currentLanguage.value == AppLanguage.PERSIAN

    val strings: AppStrings
        get() = if (isPersian) PersianStrings else EnglishStrings

    val layoutDirection: LayoutDirection
        get() = if (isPersian) LayoutDirection.Rtl else LayoutDirection.Ltr
}

